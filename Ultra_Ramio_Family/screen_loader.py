def send_tab_binary(tableau):
    """Envoie une map en binaire :

    - 2 cases de 4 bits par octet
    - 0xFE à la fin de chaque ligne
    - 0xFF à la fin du tableau
    """

    if ser is None:
        print("Impossible d'envoyer : STM32 non connectée.")
        return

    for row in tableau:
        for i in range(0, len(row), 2):
            first = row[i] & 0x0F

            if i + 1 < len(row):
                second = row[i + 1] & 0x0F
            else:
                second = 0

            byte = (first << 4) | second
            print(byte , end="")

            ser.write(bytes([byte]))

        # Fin de ligne
        print("")
        ser.write(bytes([0xFE]))

    # Fin du tableau
    ser.write(bytes([0xFF]))

    ser.flush()
    print("tableau envoyé")


